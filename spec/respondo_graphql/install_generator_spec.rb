# frozen_string_literal: true

require "spec_helper"
require "fileutils"
require "tmpdir"
require "stringio"

# Railties must be loaded before rails/generators is required
# (railties is a development dependency in the gemspec).
require "rails/generators"
require "rails/generators/base"

require "generators/respondo_graphql/install/install_generator"

RSpec.describe RespondoGraphql::Generators::InstallGenerator do
  # Swap $stdin / $stdout around the block, restore in ensure.
  def with_io(input_str)
    old_in  = $stdin
    old_out = $stdout
    $stdin  = StringIO.new(input_str)
    $stdout = StringIO.new
    yield
  ensure
    $stdin  = old_in
    $stdout = old_out
  end

  def run_generator(*answers, dest:)
    with_io(answers.join("\n") + "\n") do
      described_class.new([], {}, destination_root: dest).run_interactive_setup
    end
  end

  def capture_run(*answers, dest:)
    old_in  = $stdin
    old_out = $stdout
    captured = StringIO.new
    $stdin   = StringIO.new(answers.join("\n") + "\n")
    $stdout  = captured
    described_class.new([], {}, destination_root: dest).run_interactive_setup
    captured.string
  ensure
    $stdin  = old_in
    $stdout = old_out
  end

  def initializer_path(dest)
    File.join(dest, "config", "initializers", "respondo_graphql.rb")
  end

  def initializer_content(dest)
    File.read(initializer_path(dest), encoding: "UTF-8")
  end

  # Prompt order:
  #   1. ready?              y
  #   2. api version         v2
  #   3. request_id?         y
  #   4. camelize?           y
  #   5. always HTTP 200?    y
  HAPPY_ANSWERS = %w[y v2 y y y].freeze

  describe "when user declines setup" do
    let(:dest) { Dir.mktmpdir("respondo_graphql_skip_") }
    after      { FileUtils.rm_rf(dest) }

    it "does not create the initializer" do
      run_generator("n", dest: dest)
      expect(File.exist?(initializer_path(dest))).to be false
    end

    it "prints the skip message with the re-run hint" do
      output = capture_run("n", dest: dest)
      expect(output).to include("Skipped")
      expect(output).to include("rails generate respondo_graphql:install")
    end
  end

  describe "happy path" do
    let(:dest)    { Dir.mktmpdir("respondo_graphql_happy_") }
    let(:content) { initializer_content(dest) }
    after         { FileUtils.rm_rf(dest) }

    before { run_generator(*HAPPY_ANSWERS, dest: dest) }

    it "creates config/initializers/respondo_graphql.rb" do
      expect(File.exist?(initializer_path(dest))).to be true
    end

    it "starts with the frozen string literal comment" do
      expect(content).to start_with("# frozen_string_literal: true")
    end

    it "writes the origin comment and version" do
      expect(content).to include("# Generated by: rails generate respondo_graphql:install")
      expect(content).to include("# RespondoGraphql version: #{RespondoGraphql::VERSION}")
    end

    it "wraps config in a RespondoGraphql.configure block" do
      expect(content).to include("RespondoGraphql.configure do |config|")
      expect(content).to end_with("end\n")
    end

    it "writes the chosen options" do
      expect(content).to include("config.include_request_id = true")
      expect(content).to include("config.camelize_keys = true")
      expect(content).to include("config.always_ok = true")
    end

    it "writes the api version into default_meta" do
      expect(content).to include('config.default_meta = { api_version: "v2" }')
    end

    it "writes the data key and a commented auto_include hint" do
      expect(content).to include("config.data_key = :result")
      expect(content).to include("# config.auto_include = false")
    end

    it "produces valid Ruby that configures RespondoGraphql" do
      expect { RubyVM::InstructionSequence.compile(content) }.not_to raise_error
      eval(content) # rubocop:disable Security/Eval
      expect(RespondoGraphql.config.always_ok).to          eq(true)
      expect(RespondoGraphql.config.camelize_keys).to      eq(true)
      expect(RespondoGraphql.config.default_meta).to       eq(api_version: "v2")
    end
  end

  describe "default values" do
    let(:dest)    { Dir.mktmpdir("respondo_graphql_defaults_") }
    let(:content) { initializer_content(dest) }
    after         { FileUtils.rm_rf(dest) }

    # ready=y, blank api version, n for the rest
    before { run_generator("y", "", "n", "n", "n", dest: dest) }

    it "defaults api_version to v1" do
      expect(content).to include('api_version: "v1"')
    end

    it "defaults every option to false" do
      expect(content).to include("config.include_request_id = false")
      expect(content).to include("config.camelize_keys = false")
      expect(content).to include("config.always_ok = false")
    end
  end

  describe "when input ends early" do
    let(:dest) { Dir.mktmpdir("respondo_graphql_eof_") }
    after      { FileUtils.rm_rf(dest) }

    it "falls back to defaults instead of failing" do
      run_generator("y", dest: dest)
      expect(initializer_content(dest)).to include("config.always_ok = false")
    end
  end

  describe "terminal output" do
    let(:dest)   { Dir.mktmpdir("respondo_graphql_out_") }
    let(:output) { capture_run(*HAPPY_ANSWERS, dest: dest) }
    after        { FileUtils.rm_rf(dest) }

    it "prints the version" do
      expect(output).to include(RespondoGraphql::VERSION)
    end

    it "prints Configuration Summary exactly once" do
      expect(output.scan("Configuration Summary").size).to eq(1)
    end

    it "lists the chosen values in the summary" do
      expect(output).to include("API version:")
      expect(output).to include("Always HTTP 200:")
    end

    it "confirms the file was created and prints the done banner" do
      expect(output).to include("✅")
      expect(output).to include("config/initializers/respondo_graphql.rb")
      expect(output).to include("RespondoGraphql is ready!")
    end

    it "shows every section header" do
      ["API version", "Request ID", "Key Format", "HTTP status"].each { |h| expect(output).to include(h) }
    end
  end

  describe "re-running the generator" do
    let(:dest) { Dir.mktmpdir("respondo_graphql_rerun_") }
    after      { FileUtils.rm_rf(dest) }

    it "overwrites the existing initializer" do
      run_generator(*HAPPY_ANSWERS, dest: dest)
      run_generator("y", "v3", "n", "n", "n", dest: dest)
      content = initializer_content(dest)
      expect(content).to include('api_version: "v3"')
      expect(content).not_to include('"v2"')
    end
  end

  describe "build_content — blank api_version branch" do
    let(:dest) { Dir.mktmpdir("respondo_graphql_blank_") }
    after      { FileUtils.rm_rf(dest) }

    it "writes config.default_meta = {} when api_version is blank" do
      gen = described_class.new([], {}, destination_root: dest)
      gen.instance_variable_set(:@cfg, { api_version: "", include_request_id: false, camelize_keys: false, always_ok: false })
      expect(gen.send(:build_content)).to include("config.default_meta = {}")
    end

    it "shows (none) for a blank api_version in the summary" do
      old_out = $stdout
      $stdout = out = StringIO.new
      gen = described_class.new([], {}, destination_root: dest)
      gen.instance_variable_set(:@cfg, { api_version: "", include_request_id: false, camelize_keys: false, always_ok: false })
      gen.send(:print_summary)
      expect(out.string).to include("(none)")
    ensure
      $stdout = old_out
    end
  end
end
