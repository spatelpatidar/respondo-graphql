# frozen_string_literal: true

require "rails/generators"
require "fileutils"

module RespondoGraphql
  module Generators
    # rails generate respondo_graphql:install
    #
    # Asks a few questions and writes config/initializers/respondo_graphql.rb.
    # All output goes through $stdout (never Thor's `say`) so it is not echoed twice.
    class InstallGenerator < Rails::Generators::Base
      desc "Interactive setup — creates config/initializers/respondo_graphql.rb with your preferences."

      def run_interactive_setup
        out banner
        out blank

        unless confirm("  Ready to configure RespondoGraphql? (y/n) ")
          out blank
          out line(yellow("  Skipped. Run this again any time:"))
          out line("    rails generate respondo_graphql:install")
          out blank
          return
        end

        @cfg = {}

        step_api_version
        step_request_id
        step_camelize
        step_always_ok

        print_summary
        write_initializer
        print_done
      end

      private

      # =========================================================================
      # Steps
      # =========================================================================

      def step_api_version
        out section("API version")
        out line("  Added to the extensions block of every response (e.g. v1, v2).")
        out blank
        @cfg[:api_version] = prompt_default("v1")
      end

      def step_request_id
        out section("Request ID")
        out line("  Include Rails request.request_id in every response's extensions —")
        out line("  useful for log correlation and debugging.")
        out blank
        @cfg[:include_request_id] = confirm("  Include request_id in every response? (y/n) ")
      end

      def step_camelize
        out section("Key Format")
        out line("  CamelCase all response keys:")
        out line(yellow('    { "data": { "createdAt": "...", "userId": 1 } }'))
        out blank
        @cfg[:camelize_keys] = confirm("  Camelize all response keys? (y/n) ")
      end

      def step_always_ok
        out section("HTTP status")
        out line("  Many GraphQL clients (e.g. Apollo) treat non-2xx responses as network")
        out line("  errors. Answer y to always send HTTP 200 and report failures in `errors`.")
        out line("  Answer n to keep each helper's status (404 for render_graphql_not_found, ...).")
        out blank
        @cfg[:always_ok] = confirm("  Always send HTTP 200? (y/n) ")
      end

      # =========================================================================
      # Summary
      # =========================================================================

      def print_summary
        out blank
        out divider
        out line(cyan("  Configuration Summary"))
        out divider
        out blank
        summary_row "API version",        api_version.empty? ? "(none)" : api_version
        summary_row "Include request_id", @cfg[:include_request_id]
        summary_row "Camelize keys",      @cfg[:camelize_keys]
        summary_row "Always HTTP 200",    @cfg[:always_ok]
        out blank
        out divider
        out blank
      end

      def summary_row(label, value)
        shown = value == true ? green(value.inspect) : yellow(value.is_a?(String) ? value : value.inspect)
        out "  #{"#{label}:".ljust(24)}#{shown}\n"
      end

      def api_version
        @cfg[:api_version].to_s
      end

      # =========================================================================
      # Write file
      # =========================================================================

      def write_initializer
        dir  = File.join(destination_root, "config", "initializers")
        path = File.join(dir, "respondo_graphql.rb")
        FileUtils.mkdir_p(dir)
        File.write(path, build_content)
        out line(green("  ✅  Created config/initializers/respondo_graphql.rb"))
        out blank
      end

      def build_content
        lines = []
        lines << "# frozen_string_literal: true"
        lines << ""
        lines << "# RespondoGraphql initializer"
        lines << "# Generated by: rails generate respondo_graphql:install"
        lines << "# RespondoGraphql version: #{RespondoGraphql::VERSION}"
        lines << ""
        lines << "RespondoGraphql.configure do |config|"
        lines << "  # Fallback messages when a helper is called without message:"
        lines << "  config.default_success_message = \"Success\""
        lines << "  config.default_error_message   = \"An error occurred\""
        lines << ""
        lines << "  # Include Rails request.request_id in every response's extensions."
        lines << "  config.include_request_id = #{@cfg[:include_request_id] ? true : false}"
        lines << ""
        lines << "  # CamelCase all response keys."
        lines << "  config.camelize_keys = #{@cfg[:camelize_keys] ? true : false}"
        lines << ""
        lines << "  # Send every response with HTTP 200; failures are reported in `errors`."
        lines << "  config.always_ok = #{@cfg[:always_ok] ? true : false}"
        lines << ""
        lines << "  # GraphQL `data` must be a map: Array / scalar payloads are wrapped under this key."
        lines << "  config.data_key = :result"
        lines << ""
        lines << "  # Static fields merged into the extensions block of every response."
        lines << (api_version.empty? ? "  config.default_meta = {}" : "  config.default_meta = { api_version: #{api_version.inspect} }")
        lines << ""
        lines << "  # Custom serializer — receives the payload, returns a Hash/Array."
        lines << "  # config.serializer = ->(obj) { MySerializer.new(obj).as_json }"
        lines << ""
        lines << "  # render_graphql_ok, render_graphql_not_found, ... work in every controller"
        lines << "  # with no include. Without the respondo (JSON) gem, render_ok, render_not_found, ..."
        lines << "  # work too. With respondo installed its render_ok stays JSON; to get the short"
        lines << "  # names as GraphQL in one controller, add"
        lines << "  #   include RespondoGraphql::ShortHelpers"
        lines << "  # to that controller."
        lines << "end"
        lines << ""
        lines.join("\n")
      end

      # =========================================================================
      # Done
      # =========================================================================

      def print_done
        out divider
        out blank
        out line(cyan("  🎉  RespondoGraphql is ready!"))
        out blank
        out line("  Next steps:")
        out line("    1. Review   config/initializers/respondo_graphql.rb")
        out line("    2. Use      render_graphql_ok / render_graphql_not_found / ... in your controllers")
        out line("    3. Re-run   rails generate respondo_graphql:install  to regenerate")
        out blank
        out divider
        out blank
      end

      # =========================================================================
      # Output primitives — all output goes through $stdout, never through Thor
      # =========================================================================

      def out(str)
        $stdout.print str
        $stdout.flush
      end

      def line(str)
        "#{str}\n"
      end

      def blank
        "\n"
      end

      def divider
        "  #{cyan("─" * 68)}\n"
      end

      def section(title)
        dashes = "─" * [0, 54 - title.length].max
        "\n  #{cyan("┌─ #{title} #{dashes}┐")}\n\n"
      end

      def banner
        green("\n  RespondoGraphql — GraphQL-spec responses for Rails  (v#{RespondoGraphql::VERSION})\n")
      end

      def prompt_default(default)
        $stdout.print "  #{cyan("›")} #{yellow("[#{default}]")}: "
        $stdout.flush
        result = $stdin.gets.to_s.strip
        result.empty? ? default.to_s : result
      end

      def confirm(question)
        $stdout.print question
        $stdout.flush
        $stdin.gets.to_s.strip.downcase.start_with?("y")
      end

      def cyan(text)   = "\e[36m#{text}\e[0m"
      def green(text)  = "\e[32m#{text}\e[0m"
      def yellow(text) = "\e[33m#{text}\e[0m"
    end
  end
end
